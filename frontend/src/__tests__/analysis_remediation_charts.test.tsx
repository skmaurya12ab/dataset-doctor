describe('ApprovalModal Human-In-The-Loop Boundary', () => {
  it('strictly disables approval button until user toggles approval checkbox', () => {
    const handleApprove = vi.fn()
    render(
      <ApprovalModal
        isOpen={true}
        onClose={vi.fn()}
        onApprove={handleApprove}
        transformationSpecs={[
          {
            action: 'DROP_COLUMN',
            column: 'redundant_id',
            parameters: {},
            rationale: 'Drop uninformative column',
            source_issue_ids: [],
          },
        ]}
        isApplying={false}
      />,
    )

    const submitBtn = screen.getByRole('button', { name: /Approve & Apply/i })
    expect(submitBtn).toBeDisabled()

    // Click checkbox
    const checkbox = screen.getByRole('checkbox')
    fireEvent.click(checkbox)
    expect(submitBtn).toBeEnabled()

    // Submit
    fireEvent.click(submitBtn)
    expect(handleApprove).toHaveBeenCalled()
  })
})
