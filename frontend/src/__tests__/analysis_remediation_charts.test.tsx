vi.mock('../services/api')

describe('Analysis Trigger API Client Regression Contract (Commit 89bf5fc)', () => {
  it('calls POST /datasets/:datasetId/versions/:versionId/analyze and NEVER /analyses', async () => {
    // Mock the triggerAnalysis method and assert on its invocation
    vi.mocked(api.triggerAnalysis).mockResolvedValue({
      analysis_run_id: 'mock-run-777',
      status: 'PENDING',
    })

    const result = await api.triggerAnalysis('ds-alpha', 'ver-omega', {
      target_column: 'churn_label',
      problem_type: 'classification',
    })

    expect(result.analysis_run_id).toBe('mock-run-777')
    expect(result.status).toBe('PENDING')
    expect(api.triggerAnalysis).toHaveBeenCalledWith(
      'ds-alpha',
      'ver-omega',
      expect.objectContaining({
        target_column: 'churn_label',
        problem_type: 'classification',
      }),
    )
  })
})

describe('UploadModal Flow & Validation', () => {
  it('renders modal with accepted file formats', () => {
    render(
      <UploadModal
        isOpen={true}
        onClose={vi.fn()}
        onSuccess={vi.fn()}
      />,
    )

    expect(screen.getByText('Upload New Dataset')).toBeInTheDocument()
    expect(screen.getByText(/Click or drag file to upload/i)).toBeInTheDocument()
    expect(screen.getByText(/Supported formats: CSV, XLSX, JSON, Parquet/i)).toBeInTheDocument()
  })

  it('submits valid file and metadata via API', async () => {
    vi.mocked(api.uploadDataset).mockResolvedValue({
      dataset_id: 'ds-new-1',
      version_id: 'ver-new-1',
      version_number: 1,
      file_name: 'test.csv',
      row_count: 100,
      column_count: 5,
      storage_format: 'parquet',
      status: 'CREATED',
    })

    const handleSuccess = vi.fn()
    render(
      <UploadModal
        isOpen={true}
        onClose={vi.fn()}
        onSuccess={handleSuccess}
      />,
    )

    // Fill dataset name
    const nameInput = screen.getByPlaceholderText(/e\.g\. Customer Churn 2026/i)
    fireEvent.change(nameInput, { target: { value: 'Marketing Leads 2026' } })

    // Simulate file input
    const file = new File(['col1,col2\n1,2'], 'leads.csv', { type: 'text/csv' })
    const fileInput = document.querySelector('input[type="file"]') as HTMLInputElement
    if (fileInput) {
      fireEvent.change(fileInput, { target: { files: [file] } })
    }

    const uploadButton = screen.getByRole('button', { name: /Upload Dataset/i })
    fireEvent.click(uploadButton)

    await waitFor(() => {
      expect(api.uploadDataset).toHaveBeenCalled()
    })

    await waitFor(
      () => {
        expect(handleSuccess).toHaveBeenCalledWith(
          expect.objectContaining({ dataset_id: 'ds-new-1', version_id: 'ver-new-1' }),
        )
      },
      { timeout: 2500 },
    )
  })
})

describe('PlotlyChart Integration', () => {
  it('renders mock plotly container with data and layout attributes', () => {
    const mockData = [{ x: [1, 2, 3], y: [10, 20, 30], type: 'bar' as const }]
    const mockLayout = { title: { text: 'Test Chart' } }

    render(<PlotlyChart data={mockData} layout={mockLayout} />)

    const chartEl = screen.getByTestId('plotly-mock')
    expect(chartEl).toBeInTheDocument()
    expect(chartEl).toHaveAttribute(
      'data-plot-data',
      JSON.stringify(mockData),
    )
  })

  it('handles empty chart data gracefully without throwing', () => {
    render(<PlotlyChart data={[]} />)
    const chartEl = screen.getByTestId('plotly-mock')
    expect(chartEl).toBeInTheDocument()
    expect(chartEl).toHaveAttribute('data-plot-data', '[]')
  })
})

